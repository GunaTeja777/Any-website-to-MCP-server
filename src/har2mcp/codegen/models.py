"""Data models and formatting helpers for generated MCP server projects."""

from __future__ import annotations

import re
from typing import Any, Literal
from urllib.parse import urlparse

from pydantic import BaseModel, ConfigDict, Field

from har2mcp.auth.models import AuthSpec, AuthType
from har2mcp.design.models import ToolParameter, ToolSpec

PYTHON_TYPE_MAP: dict[str, str] = {
    "string": "str",
    "str": "str",
    "integer": "int",
    "int": "int",
    "number": "float",
    "float": "float",
    "boolean": "bool",
    "bool": "bool",
    "array": "list[Any]",
    "list": "list[Any]",
    "object": "dict[str, Any]",
    "dict": "dict[str, Any]",
}


class RenderedParameter(BaseModel):
    """Parameter formatted for Python function signature and request dispatch."""

    model_config = ConfigDict(frozen=True)

    name: str = Field(..., description="Python variable name (snake_case).")
    api_name: str = Field(..., description="API parameter or field name.")
    type_annotation: str = Field(..., description="Python type hint, e.g. 'str', 'int'.")
    description: str = Field(..., description="Parameter description for docstring.")
    required: bool = Field(default=True, description="Whether parameter is required.")
    default_value: Any | None = Field(default=None, description="Default value if optional.")
    location: Literal["path", "query", "body"] = Field(
        default="query", description="Location in HTTP request."
    )

    @property
    def python_signature(self) -> str:
        """Render Python signature snippet (e.g. 'user_id: str' or 'limit: int | None = 10')."""
        if self.required and self.default_value is None:
            return f"{self.name}: {self.type_annotation}"
        if self.default_value is not None:
            repr_val = repr(self.default_value)
            return f"{self.name}: {self.type_annotation} = {repr_val}"
        return f"{self.name}: {self.type_annotation} | None = None"


class RenderedTool(BaseModel):
    """Tool prepared for Jinja template rendering."""

    model_config = ConfigDict(frozen=True)

    name: str = Field(..., description="Python function name.")
    description: str = Field(..., description="Tool description for docstring.")
    operation_type: Literal["read", "write"] = Field(default="read")
    is_write: bool = Field(default=False)
    method: str = Field(default="GET")
    endpoint_path: str = Field(default="/")
    parameters: list[RenderedParameter] = Field(default_factory=list)
    path_params: list[RenderedParameter] = Field(default_factory=list)
    query_params: list[RenderedParameter] = Field(default_factory=list)
    body_params: list[RenderedParameter] = Field(default_factory=list)


class ServerProjectConfig(BaseModel):
    """Full configuration for generating a standalone MCP server project."""

    model_config = ConfigDict(frozen=True)

    server_name: str = Field(default="api-mcp-server")
    project_name: str = Field(default="api-mcp-server")
    description: str = Field(default="MCP server generated by HAR2MCP")
    base_url: str = Field(default="https://api.example.com")
    tools: list[RenderedTool] = Field(default_factory=list)
    auth_spec: AuthSpec = Field(
        default_factory=lambda: AuthSpec(primary_type=AuthType.NONE)
    )
    allow_writes: bool = Field(default=False)
    has_pagination: bool = Field(default=False)
    version: str = Field(default="0.1.0")


def sanitize_project_name(name: str) -> str:
    """Sanitize name to a valid PEP 508 / pyproject package name."""
    s = re.sub(r"[^a-zA-Z0-9]+", "-", name).strip("-").lower()
    return s or "mcp-server"


def resolve_python_type(raw_type: str) -> str:
    """Map JSON or loose schema type names to canonical Python type hints."""
    cleaned = raw_type.lower().strip()
    return PYTHON_TYPE_MAP.get(cleaned, "str")


def build_rendered_tool(
    tool: ToolSpec,
) -> RenderedTool:
    """Convert a ToolSpec into a RenderedTool with typed parameters and sorted signature."""
    endpoint_mapping = tool.endpoints[0] if tool.endpoints else None
    method = endpoint_mapping.method.upper() if endpoint_mapping else "GET"
    path_template = endpoint_mapping.path_template if endpoint_mapping else "/"
    param_mappings = endpoint_mapping.parameter_mappings if endpoint_mapping else {}

    # Identify path variables from template e.g. /users/{user_id}
    path_var_names = set(re.findall(r"\{([^}]+)\}", path_template))

    rendered_params: list[RenderedParameter] = []
    for p in tool.parameters:
        py_type = resolve_python_type(p.type)
        api_name = param_mappings.get(p.name, p.name)

        # Determine location
        if p.name in path_var_names or api_name in path_var_names:
            loc: Literal["path", "query", "body"] = "path"
            is_req = True  # Path parameters are always required
            default_val = None
        elif p.location in ("path", "query", "body"):
            loc = p.location
            is_req = p.required
            default_val = p.default
        elif method in ("POST", "PUT", "PATCH"):
            loc = "body"
            is_req = p.required
            default_val = p.default
        else:
            loc = "query"
            is_req = p.required
            default_val = p.default

        rendered_params.append(
            RenderedParameter(
                name=p.name,
                api_name=api_name,
                type_annotation=py_type,
                description=p.description,
                required=is_req,
                default_value=default_val,
                location=loc,
            )
        )

    # Sort parameters so non-default parameters come first (vital for valid Python syntax)
    sorted_params = sorted(
        rendered_params,
        key=lambda param: (not param.required or param.default_value is not None),
    )

    path_params = [p for p in rendered_params if p.location == "path"]
    query_params = [p for p in rendered_params if p.location == "query"]
    body_params = [p for p in rendered_params if p.location == "body"]

    return RenderedTool(
        name=tool.name,
        description=tool.description.strip(),
        operation_type=tool.operation_type,
        is_write=tool.is_write or tool.operation_type == "write",
        method=method,
        endpoint_path=path_template,
        parameters=sorted_params,
        path_params=path_params,
        query_params=query_params,
        body_params=body_params,
    )


def extract_base_url_from_endpoints(
    tool_specs: list[ToolSpec], default_base_url: str = "https://api.example.com"
) -> str:
    """Extract scheme + netloc base URL if any endpoints contain absolute URLs."""
    for tool in tool_specs:
        for ep in tool.endpoints:
            if ep.path_template.startswith("http://") or ep.path_template.startswith(
                "https://"
            ):
                parsed = urlparse(ep.path_template)
                return f"{parsed.scheme}://{parsed.netloc}"
    return default_base_url
